// Mounted browser interaction checks. No server or listening port is started.
import {build} from '../../display/node_modules/esbuild/lib/main.js';
import {resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const [playwrightEntry,evidenceDirectory]=process.argv.slice(2);
if(!playwrightEntry||!evidenceDirectory)throw new Error('Usage: node scripts/strategy-ui.mjs <playwright index.mjs> <evidence directory>');
const {chromium}=await import(pathToFileURL(resolve(playwrightEntry)).href);
const evidence=resolve(evidenceDirectory);
const fixture=fileURLToPath(new URL('./strategy-ui.fixture.jsx',import.meta.url));
const bundle=await build({entryPoints:[fixture],bundle:true,write:false,jsx:'automatic',define:{'process.env.NODE_ENV':'"development"'}});
import {readFile,mkdir} from 'node:fs/promises';
await mkdir(evidence,{recursive:true});
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
try {
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.setDefaultTimeout(5000);page.on('pageerror',error=>errors.push(error.message));
await page.setContent('<!doctype html><html lang="zh-CN"><head><title>策略参数交互测试</title></head><body><div id="root"></div></body></html>');
await page.addStyleTag({content:await readFile(new URL('../src/workbench/workbench.css',import.meta.url),'utf8')});
await page.addScriptTag({content:bundle.outputFiles[0].text});
const check=page.getByRole('button',{name:'检查参数与数据'}),run=page.getByRole('button',{name:'运行基准',exact:true});
await page.getByLabel('持股数量',{exact:true}).waitFor();
await page.evaluate(()=>window.render(window.port,window.other));
assert.equal(await page.getByLabel('持股数量',{exact:true}).count(),0);
assert.equal(await page.getByLabel('快线周期',{exact:true}).inputValue(),'20');
assert.equal(await page.getByLabel('慢线周期',{exact:true}).inputValue(),'60');
assert.equal(await page.getByLabel('资金比例',{exact:true}).inputValue(),'1');
await page.evaluate(()=>window.render());
await page.getByLabel('持股数量',{exact:true}).waitFor();
assert.equal(await page.getByLabel('回测策略',{exact:true}).count(),0);
assert.equal(await run.isEnabled(),false);
await page.getByLabel('持股数量',{exact:true}).fill('12');
await page.getByLabel('排序',{exact:true}).selectOption('large');
await page.getByLabel('开关',{exact:true}).uncheck();
await check.click();await page.getByRole('heading',{name:'检查通过'}).waitFor();
assert.equal(await run.isEnabled(),true);
await run.click();await page.getByRole('heading',{name:'回测对比'}).waitFor();
assert.equal(await page.getByText('12.00%',{exact:true}).count(),1);
assert.equal(await page.getByText('未提供',{exact:true}).count(),1);
assert.deepEqual(await page.evaluate(()=>window.calls[1][1].params),{count:12,order:'large',enabled:false,note:''});
await page.getByLabel('持股数量',{exact:true}).fill('8');
assert.equal(await page.getByRole('button',{name:'运行修改参数'}).isEnabled(),false);
await page.getByText('当前参数未运行',{exact:true}).waitFor();
await check.click();await page.getByRole('heading',{name:'检查通过'}).waitFor();
await page.getByRole('button',{name:'运行修改参数'}).click();await page.getByRole('heading',{name:'修改后',exact:true}).waitFor();
assert.equal(await page.getByText('8.00%',{exact:true}).count(),1);
await page.getByRole('button',{name:'设为新基准'}).click();
assert.equal(await page.getByRole('heading',{name:'基准',exact:true}).count(),1);
assert.equal(await page.getByText('8.00%',{exact:true}).count(),1);
await page.getByRole('button',{name:'运行修改参数'}).click();await page.getByRole('heading',{name:'同参数复跑',exact:true}).waitFor();
await page.evaluate(()=>{window.nextData='different'});await page.getByRole('button',{name:'运行修改参数'}).click();await page.getByText('不能直接比较：历史数据不同',{exact:true}).waitFor();
await page.evaluate(()=>{window.blocked=true});await check.click();await page.getByText('历史数据未验收',{exact:true}).waitFor();
assert.equal(await page.getByRole('button',{name:'运行修改参数'}).isEnabled(),false);
assert.equal(await page.getByLabel('持股数量',{exact:true}).inputValue(),'8');
await page.evaluate(()=>{window.blocked=false;window.delay=true});
await check.click();assert.equal(await page.getByRole('button',{name:'正在检查…'}).isEnabled(),false);assert.equal(await page.getByLabel('持股数量',{exact:true}).isEnabled(),false);
const count=await page.evaluate(()=>window.calls.length);
await page.evaluate(()=>{document.querySelector('form').dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}))});
assert.equal(await page.evaluate(()=>window.calls.length),count);
// Replace the core backend while an old request is pending; its response cannot overwrite the new state.
await page.evaluate(()=>{window.render({...window.port},window.other);});
await page.getByLabel('快线周期',{exact:true}).waitFor();
await page.evaluate(()=>{window.pending()});await page.waitForTimeout(30);
assert.equal(await page.getByRole('heading',{name:'检查通过'}).count(),0);
await page.evaluate(()=>{window.delay=false;window.blocked=true;window.render()});
await page.getByLabel('持股数量',{exact:true}).waitFor();await check.click();await page.getByText('历史数据未验收',{exact:true}).waitFor();
await page.screenshot({path:resolve(evidence,'desktop.png'),fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:resolve(evidence,'mobile.png'),fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
console.log('PASS: mounted UI edits numeric/enum/boolean parameters, runs two actual mocked-port requests, preserves baseline, prevents stale comparisons and duplicate submits, exposes blocked reasons, rejects stale responses; desktop/mobile no overflow and no page errors. No port opened.');
} finally {await browser.close()}
