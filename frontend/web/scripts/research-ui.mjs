// Mounted browser interaction checks. No server or listening port is started.
import {build} from '../../display/node_modules/esbuild/lib/main.js';
import {resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const [playwrightEntry,evidenceDirectory]=process.argv.slice(2);
if(!playwrightEntry||!evidenceDirectory)throw new Error('Usage: node scripts/research-ui.mjs <playwright index.mjs> <evidence directory>');
const {chromium}=await import(pathToFileURL(resolve(playwrightEntry)).href);
const evidence=resolve(evidenceDirectory);
const fixture=fileURLToPath(new URL('./research-ui.fixture.jsx',import.meta.url));
const bundle=await build({entryPoints:[fixture],bundle:true,write:false,jsx:'automatic',define:{'process.env.NODE_ENV':'"development"'}});
import {readFile,mkdir} from 'node:fs/promises';
await mkdir(evidence,{recursive:true});
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
try {
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.setDefaultTimeout(5000);page.on('pageerror',error=>errors.push(error.message));
await page.setContent('<!doctype html><html lang="zh-CN"><head><title>策略参数交互测试</title></head><body><div id="root"></div></body></html>');
await page.addStyleTag({content:await readFile(new URL('../src/workbench/workbench.css',import.meta.url),'utf8')});
await page.addScriptTag({content:bundle.outputFiles[0].text});
await page.getByRole('button',{name:'零回测策略'}).waitFor();
assert.equal(await page.getByRole('region',{name:'参数回测'}).count(),0);
assert.equal(await page.getByRole('button',{name:/新建/}).count(),0);
await page.getByRole('button',{name:'零回测策略'}).click();
await page.getByLabel('周期',{exact:true}).waitFor();
assert.equal(await page.getByLabel('回测策略',{exact:true}).count(),0);
assert.equal(await page.getByText('尚无回测记录',{exact:true}).count(),1);
await page.getByRole('heading',{name:'策略规则说明',exact:true}).waitFor();
assert.equal(await page.getByText('均线规则',{exact:true}).count(),1);
assert.equal(await page.evaluate(()=>window.calls.filter(item=>item[0]==='archive').length),0);
await page.getByRole('button',{name:'检查参数与数据'}).click();
await page.getByRole('heading',{name:'检查通过'}).waitFor();
await page.getByRole('button',{name:'运行基准',exact:true}).click();
await page.getByRole('heading',{name:'回测对比'}).waitFor();
await page.getByLabel('选择回测记录').waitFor();
assert.equal(await page.getByLabel('选择回测记录').inputValue(),'new');
assert.equal(await page.evaluate(()=>window.calls.find(item=>item[0]==='run')[1].module),'plugins.empty');
await page.getByRole('button',{name:'← 返回策略列表'}).click();
assert.equal(await page.getByLabel('周期',{exact:true}).count(),0);
await page.getByRole('button',{name:'另一策略'}).click();
await page.getByLabel('周期',{exact:true}).waitFor();
await page.evaluate(()=>window.delay=true);
await page.getByRole('button',{name:'检查参数与数据'}).click();
await page.getByRole('button',{name:'← 返回策略列表'}).click();
await page.getByRole('button',{name:'零回测策略'}).click();
await page.getByLabel('周期',{exact:true}).waitFor();
await page.evaluate(()=>{window.pending();window.delay=false});
await page.waitForTimeout(30);
assert.equal(await page.getByRole('heading',{name:'检查通过'}).count(),0);
assert.equal(await page.evaluate(()=>window.calls.filter(item=>item[0]==='catalog').length),1);
await page.getByRole('button',{name:'← 返回策略列表'}).click();
await page.getByRole('button',{name:'removed',exact:true}).click();
await page.getByRole('heading',{name:'回测概览'}).waitFor();
assert.equal(await page.getByLabel('周期',{exact:true}).count(),0);
assert.equal(await page.getByRole('heading',{name:'参数回测',exact:true}).count(),0);
await page.getByRole('button',{name:'← 返回策略列表'}).click();
await page.evaluate(()=>window.render({...window.port,strategies:async()=>{throw new Error('目录不可读取')}}));
await page.getByText('策略目录读取失败：Error: 目录不可读取',{exact:true}).waitFor();
await page.getByRole('button',{name:'removed',exact:true}).click();
await page.getByRole('heading',{name:'回测概览'}).waitFor();
assert.equal(await page.getByText('目录状态未知',{exact:true}).count(),1);
assert.equal(await page.getByText('仅存档',{exact:true}).count(),0);
assert.equal(await page.getByRole('heading',{name:'参数回测',exact:true}).count(),0);
await page.screenshot({path:resolve(evidence,'desktop.png'),fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:resolve(evidence,'mobile.png'),fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
console.log('PASS: catalog-only home, unused-plugin detail, fixed strategy, completed-run archive refresh, removed-plugin history, one catalog request and stale-request isolation; mobile no overflow and no page errors. No port opened.');
} finally {await browser.close()}
